#!/usr/bin/env python3
"""Sync simulator reference payloads from canonical processed data.

This keeps simulator/data/traits.json and simulator/data/helper_units.json
aligned with data/api/processed generated by scripts/fetch_game_data.py.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


PROJECT_ROOT = Path(__file__).resolve().parents[2]
PROCESSED_DIR = PROJECT_ROOT / "data" / "api" / "processed"
SIMULATOR_DATA_DIR = PROJECT_ROOT / "simulator" / "data"


def _load_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def _dump_json(path: Path, payload: Any) -> None:
    with path.open("w", encoding="utf-8") as handle:
        json.dump(payload, handle, indent=2, ensure_ascii=False)
        handle.write("\n")


def _normalized_trait_payload(raw_trait: dict[str, Any]) -> dict[str, Any]:
    effects = []
    for effect in raw_trait.get("effects", []):
        effects.append(
            {
                "minUnits": effect.get("minUnits"),
                "maxUnits": effect.get("maxUnits"),
                "style": effect.get("style"),
                "variables": effect.get("variables", {}),
            }
        )

    return {
        "apiName": raw_trait.get("apiName"),
        "name": raw_trait.get("name"),
        "effects": effects,
    }


def sync_traits() -> int:
    traits_path = PROCESSED_DIR / "traits_set16.json"
    traits_payload = _load_json(traits_path)

    normalized = {}
    for trait in traits_payload:
        api_name = trait.get("apiName")
        if not api_name:
            continue
        normalized[api_name] = _normalized_trait_payload(trait)

    output = {
        "set": 16,
        "source": "data/api/processed/traits_set16.json",
        "last_updated": datetime.now(timezone.utc).isoformat(),
        "traits": normalized,
    }

    _dump_json(SIMULATOR_DATA_DIR / "traits.json", output)
    return len(normalized)


def sync_helper_units() -> int:
    units_path = PROCESSED_DIR / "units_set16.json"
    units_payload = _load_json(units_path)

    helper_units = []
    for unit in units_payload:
        if not unit.get("is_helper", False):
            continue
        helper_units.append(
            {
                "apiName": unit.get("apiName"),
                "name": unit.get("name"),
                "cost": unit.get("cost"),
                "traits": unit.get("traits", []),
                "icon": unit.get("icon"),
            }
        )

    helper_units.sort(key=lambda entry: entry.get("apiName") or "")
    output = {
        "set": 16,
        "source": "data/api/processed/units_set16.json",
        "last_updated": datetime.now(timezone.utc).isoformat(),
        "helpers": helper_units,
    }

    _dump_json(SIMULATOR_DATA_DIR / "helper_units.json", output)
    return len(helper_units)


def main() -> int:
    traits_count = sync_traits()
    helper_count = sync_helper_units()
    print(
        f"Synced simulator reference data: {traits_count} traits, "
        f"{helper_count} helper units"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
